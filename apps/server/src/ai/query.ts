/**
 * 查询 / 读取类任务的识别与执行规范。
 *
 * 这类任务的目标是「拿到屏幕上的信息」，不是完成一串操作。
 * 和通用操作任务相比，它应该：
 * - 能直接回答就不做任何动作；
 * - 需要进入页面时只做最少的点击，不走 plan、不来回滑动；
 * - 最终由模型做语义提取，而不是把屏幕文字整段抄下来。
 */

/** 明显是「要信息」的说法。命中后仍要排除写操作。 */
const QUERY_PATTERN =
  /(看一下|看看|查看|查|查询|读取|读出|念一下|显示什么|显示的是|显示啥|是什么|是多少|多少|有没有|是否|怎么样|如何|最近|最新|第一条|最后一条|顶部|当前页面|现在.*(?:什么|多少))/;

/** 会修改数据 / 产生外部影响的动作，命中时按操作任务处理。 */
const MUTATION_PATTERN =
  /(发送|发消息|发给|转发|提交|输入|填写|删除|修改|设置|开启|关闭|安装|卸载|支付|转账|点赞|关注|下单|购买|清空|标记为|退出登录)/;

export function isQueryTask(instruction: string): boolean {
  const text = instruction.trim();
  if (!text) return false;
  // 「删除最近一条消息」这类先匹配到动作词，避免误判成查询
  if (MUTATION_PATTERN.test(text)) return false;
  return QUERY_PATTERN.test(text);
}

